/**
 * Built-in themes (SPEC section 9). Seeds are brand hues and are never consumed by
 * components directly; components use role tokens only (section 9.1.1).
 * This module is the single source of truth: SCSS maps, CSS custom properties,
 * tokens.json, and the contrast gate are all generated from it.
 */

export type ThemeMode = 'light' | 'dark' | 'high-contrast';
export type ContrastKind = 'text' | 'large-text' | 'non-text';

export interface ContrastPair {
  readonly foreground: string;
  readonly background: string;
  /** Optional backdrop used to composite a translucent background token. */
  readonly backdrop?: string;
  readonly kind: ContrastKind;
  readonly usage: string;
}

export type TokenMap = Readonly<Record<string, string>>;

export interface ThemeDefinition {
  readonly schemaVersion: 1;
  readonly name: string;
  readonly mode: ThemeMode;
  readonly seeds: TokenMap;
  readonly tokens: TokenMap;
  readonly contrastPairs: readonly ContrastPair[];
}

