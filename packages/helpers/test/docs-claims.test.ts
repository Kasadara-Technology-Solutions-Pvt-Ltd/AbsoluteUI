import { expect, it } from 'vitest';
import { createBusinessCalendar, fixedHoliday, diffDays, isWeekend, isBusinessDay, isHoliday, getBusinessDay, describeBusinessDay, addBusinessDays, nextBusinessDay, lastBusinessDayOfMonth, adjustBusinessDay, slaDeadline, diffBusinessHours, weekendForLocale } from '@absoluteui/helpers/business-calendar';
import { formatPlainDate } from '@absoluteui/helpers/date';
import { decimal } from '@absoluteui/helpers/decimal';
import { formatBytes } from '@absoluteui/helpers/number';
import { toNumber } from '@absoluteui/helpers/convert';
it('matches the results quoted in the documentation guides', () => {
  const xmas = createBusinessCalendar({ holidays: [fixedHoliday('Christmas', 12, 25), fixedHoliday('New Year', 1, 1)] });
  expect([diffDays('2026-12-25', '2027-01-01', { mode: 'calendar', calendar: xmas }), diffDays('2026-12-25', '2027-01-01', { mode: 'weekdays', calendar: xmas }), diffDays('2026-12-25', '2027-01-01', { mode: 'business', calendar: xmas })]).toEqual([7, 5, 4]);
  const c = createBusinessCalendar({});
  expect((['start', 'both', 'end', 'none'] as const).map((i) => diffDays('2026-10-05', '2026-10-09', { mode: 'business', inclusive: i, calendar: c }))).toEqual([4, 5, 4, 3]);
  expect(diffDays('2026-10-09', '2026-10-05', { mode: 'business', calendar: c })).toBe(-4);
  const gulf = createBusinessCalendar({ weekend: [5, 6], holidays: [fixedHoliday('National Day', 12, 2)] });
  expect([isWeekend('2026-10-02', gulf), isBusinessDay('2026-10-04', gulf), isHoliday('2026-12-02', gulf)?.name]).toEqual([true, true, 'National Day']);
  const info = getBusinessDay('2026-12-02', gulf);
  expect([info.working, info.reasonCode, describeBusinessDay(info)]).toEqual([false, 'holiday', 'Holiday: National Day']);
  expect(weekendForLocale('ar-SA')).toEqual([5, 6]);
  const f = createBusinessCalendar({ holidays: [fixedHoliday('Founders Day', 10, 7)] });
  expect(diffDays('2026-10-05', '2026-10-09', { mode: 'business', inclusive: 'both', calendar: f })).toBe(4);
  expect([addBusinessDays('2026-10-09', 3, c), addBusinessDays('2026-10-09', -3, c), nextBusinessDay('2026-10-10', c), lastBusinessDayOfMonth(2026, 10, c), adjustBusinessDay('2026-10-31', 'modifiedFollowing', c)].map((d) => (d ? formatPlainDate(d) : ''))).toEqual(['2026-10-14', '2026-10-06', '2026-10-12', '2026-10-30', '2026-10-30']);
  const support = createBusinessCalendar({ timeZone: 'Europe/London', workingHours: { default: [['09:00', '17:00']] } });
  const opened = Date.parse('2026-10-09T15:00:00Z');
  const due = slaDeadline(opened, { businessHours: 4 }, support);
  expect(new Date(due).toISOString()).toBe('2026-10-12T11:00:00.000Z');
  expect(diffBusinessHours(opened, due, support)).toBe(4);
  expect(decimal('100.00').allocate([1, 1, 1], { scale: 2 }).map(String)).toEqual(['33.34', '33.33', '33.33']);
  expect(decimal('0.1').add('0.2').toString()).toBe('0.3');
  expect(formatBytes(2_400_000, { style: 'long' })).toBe('2.4 megabytes');
  expect(toNumber('12abc')).toBeUndefined();
});
