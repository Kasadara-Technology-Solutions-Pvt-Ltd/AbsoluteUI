/** Write the application sources for the frames. */
function writeWorkspace(frames, entries) {
  const byEntry = new Map(entries.map((e) => [e.entry, e.meta]));
  clean(join(workDir, 'src'));
  write(join(workDir, 'angular.json'), `${JSON.stringify(ANGULAR_JSON, null, 2)}\n`);
  write(join(workDir, 'tsconfig.json'), `${JSON.stringify(TSCONFIG, null, 2)}\n`);
  write(join(workDir, 'src', 'index.html'), INDEX);
  write(join(workDir, 'src', 'main.ts'), MAIN);
  const loaders = [];
  for (const [entry, list] of frames) {
    const boot = (byEntry.get(entry)?.example ?? []).find(isBootstrap);
    const extra = boot ? bootstrapProviders(boot.code) : null;
    if (extra?.providers.length) {
      write(join(workDir, 'src', 'examples', `${entry}.providers.ts`), [...extra.imports, '', `export const providers = [${extra.providers.join(', ')}];`, ''].join('\n'));
    }
    for (const frame of list) {
      // Root-relative image paths in the shown code ('/images/x.png') are served under the docs base (OS-3), as in the vanilla frames.
      write(join(workDir, 'src', 'examples', `${frame.id}.ts`), `${frame.block.code.replaceAll("'/images/", `'${BASE}/images/`)}\n`);
      const component = `import('./examples/${frame.id}').then((m) => m.${frame.component})`;
      loaders.push(
        extra?.providers.length
          ? `  '${frame.id}': async () => ({ component: await ${component}, providers: (await import('./examples/${entry}.providers')).providers }),`
          : `  '${frame.id}': async () => ({ component: await ${component}, providers: [] }),`,
      );
    }
  }
  write(
    join(workDir, 'src', 'examples.ts'),
    [
      '// Generated by apps/site/scripts/lib/angular-frames.mjs.',
      "import type { EnvironmentProviders, Provider, Type } from '@angular/core';",
      '',
      'export interface FrameExample {',
      '  readonly component: Type<unknown>;',
      '  readonly providers: readonly (Provider | EnvironmentProviders)[];',
      '}',
      '',
      'export const EXAMPLES: Readonly<Record<string, () => Promise<FrameExample>>> = {',
      ...loaders,
      '};',
      '',
    ].join('\n'),
  );
}

/**
 * CSP hashes of every component style Angular can inject: each string of a `styles` array in
 * the built chunks. Angular 22 replaces the CSS-variable namespace placeholder `%NS%` before
 * injecting (empty unless an application configures one), so hash the replaced text.
 */
function styleHashes(dir) {
  const hashes = new Set();
  const visit = (node) => {
    if (!node || typeof node.type !== 'string') return;
    if (node.type === 'Property' && !node.computed && (node.key.name ?? node.key.value) === 'styles' && node.value.type === 'ArrayExpression') {
      for (const el of node.value.elements) {
        let text;
        if (el?.type === 'Literal' && typeof el.value === 'string') text = el.value;
        else if (el?.type === 'TemplateLiteral' && el.expressions.length === 0) text = el.quasis[0].value.cooked;
        if (text === undefined) throw new Error('angular-frames: a component `styles` entry is not a string literal; its CSP hash cannot be computed');
        hashes.add(`'sha256-${createHash('sha256').update(text.replaceAll('%NS%', '')).digest('base64')}'`);
      }
    }
    for (const value of Object.values(node)) {
      if (Array.isArray(value)) value.forEach(visit);
      else if (value && typeof value === 'object') visit(value);
    }
  };
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.js')).sort()) {
    visit(parse(readFileSync(join(dir, file), 'utf8'), { ecmaVersion: 'latest', sourceType: 'module' }));
  }
  return [...hashes].sort();
}

/** One page per example; scripts come from the built index (`main-*.js` and its preloads). */
function framePage(frame, title, scripts, hashes) {
  const csp = CSP.replace("style-src 'self'", `style-src 'self' ${hashes.join(' ')}`);
  const links = ['fonts', 'theme', 'base'].map((s) => `<link rel="stylesheet" href="../../css/${s}.css">`).join('\n');
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="${csp}">
<meta name="robots" content="noindex">
<title>${escapeHtml(title)} | Angular example</title>
${links}
${scripts.map((s) => (s.preload ? `<link rel="modulepreload" href="../${s.file}">` : `<script type="module" src="../${s.file}"></script>`)).join('\n')}
</head>
<body>
<frame-root data-example="${escapeHtml(frame.id)}"></frame-root>
</body>
</html>
`;
}

/**
 * Build the frames and write them under public/examples/angular/. Returns, per entry, the
 * frame markup for each example block: Map<entry, Map<block code, figure html>>.
 * Run after buildExamples (it cleans public/examples and writes the shared CSS).
 */
export function buildAngularFrames(entries) {
  const frames = angularFrames(entries);
  writeWorkspace(frames, entries);
  const started = Date.now();
  execFileSync(process.execPath, [join(root, 'node_modules', '@angular', 'cli', 'bin', 'ng.js'), 'build'], {
    cwd: workDir,
    stdio: ['ignore', 'pipe', 'inherit'],
    env: { ...process.env, NG_CLI_ANALYTICS: 'false' },
  });
  const built = join(workDir, 'dist', 'browser');
  const index = readFileSync(join(built, 'index.html'), 'utf8');
  const scripts = [
    ...[...index.matchAll(/<link rel="modulepreload" href="([^"]+)"/g)].map((m) => ({ file: m[1], preload: true })),
    ...[...index.matchAll(/<script src="([^"]+)" type="module"><\/script>/g)].map((m) => ({ file: m[1], preload: false })),
  ];
  if (!scripts.some((s) => !s.preload)) throw new Error('angular-frames: no module script in the built index.html');
  const hashes = styleHashes(built);

  clean(outDir);
  for (const file of readdirSync(built).filter((f) => f.endsWith('.js'))) copyFileSync(join(built, file), join(outDir, file));
  // The bundled Angular framework code is MIT licensed; its notices ship with the frames.
  const licenses = join(workDir, 'dist', '3rdpartylicenses.txt');
  if (existsSync(licenses)) copyFileSync(licenses, join(outDir, '3rdpartylicenses.txt'));

  const markup = new Map();
  let count = 0;
  for (const [entry, list] of frames) {
    const title = angularTitle(entry, entries.find((e) => e.entry === entry).meta);
    const byCode = new Map();
    for (const frame of list) {
      write(join(outDir, frame.id, 'index.html'), framePage(frame, title, scripts, hashes));
      const min = POPUP.has(entry) ? 440 : 180;
      byCode.set(frame.block.code, `<figure class="aui-live" data-min-height="${String(min)}"><iframe data-src="${EXAMPLES_URL}/angular/${frame.id}/" title="Live Angular example: ${escapeHtml(title)}" loading="lazy"></iframe></figure>`);
      count++;
    }
    markup.set(entry, byCode);
  }
  console.log(`angular-frames: ${String(count)} frames, ${String(hashes.length)} style hashes (${String(Date.now() - started)} ms)`);
  return markup;
}
