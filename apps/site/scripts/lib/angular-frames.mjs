// Live Angular example frames (docs/PLAN-R12-ANGULAR-FRAMES.md, R12-1 to R12-6): every Angular
// example shown on the site (packages/angular/metadata/<entry>.json `example`, from section 34)
// is built ahead of time into one Angular application and shown in a frame below its code.
// Each frame page names its example; the application loads it lazily and mounts it on a `**`
// route. The frame CSP stays strict: Angular injects component styles as <style> elements,
// so every `styles` string in the built chunks is hashed into `style-src` (F0 findings).
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse } from 'acorn';
import { angularTitle } from './angular.mjs';
import { CSP, POPUP, escapeHtml } from './examples.mjs';
import { BASE, EXAMPLES_URL, clean, publicDir, root, siteDir, write } from './shared.mjs';

/** Workspace of the generated application; under apps/site so `@angular/build` resolves. */
const workDir = join(siteDir, '.cache', 'angular-frames');
const outDir = join(publicDir, 'examples', 'angular');

/** The renderable blocks of an entry's example: every block except a bootstrap block. */
const isBootstrap = (block) => /\bbootstrapApplication\(/.test(block.code);

/**
 * Frames per entry, in example order: `{ id, block, component }`. An example renders when it
 * is TypeScript that declares exactly one exported Angular component.
 * @param {Array<{ entry: string, meta: { example?: Array<{ language: string, code: string }> } }>} entries
 */
export function angularFrames(entries) {
  const frames = new Map();
  for (const { entry, meta } of entries) {
    const blocks = (meta.example ?? []).filter((b) => b.language === 'ts' && !isBootstrap(b));
    const list = [];
    for (const block of blocks) {
      const classes = [...block.code.matchAll(/@Component\(\{[\s\S]*?\}\)\s*export class (\w+)/g)].map((m) => m[1]);
      if (classes.length !== 1) throw new Error(`angular-frames: ${entry}: expected one exported component per example block, found ${String(classes.length)}`);
      list.push({ id: blocks.length > 1 ? `${entry}-${String(list.length + 1)}` : entry, block, component: classes[0] });
    }
    if (list.length) frames.set(entry, list);
  }
  return frames;
}

/**
 * Extra providers from an example's bootstrap block (`bootstrapApplication(App, { providers: [...] })`).
 * `provideAbsoluteUI(...)` is left out: the frame provides it with the docs toolbar settings.
 */
function bootstrapProviders(code) {
  const start = code.indexOf('providers: [');
  if (start < 0) return null;
  let depth = 0;
  let item = '';
  const items = [];
  for (const ch of code.slice(start + 'providers: ['.length)) {
    if (depth === 0 && ch === ']') break;
    if ('([{'.includes(ch)) depth++;
    if (')]}'.includes(ch)) depth--;
    if (depth === 0 && ch === ',') {
      items.push(item.trim());
      item = '';
    } else item += ch;
  }
  if (item.trim()) items.push(item.trim());
  const imports = [...code.matchAll(/^import [^;]+;$/gm)].map((m) => m[0]).filter((line) => !/'@angular\/platform-browser'|'\.\//.test(line));
  return { imports, providers: items.filter((p) => !p.startsWith('provideAbsoluteUI(')) };
}

const MAIN = `// Generated by apps/site/scripts/lib/angular-frames.mjs.
import { Component, provideZonelessChangeDetection } from '@angular/core';
import { bootstrapApplication } from '@angular/platform-browser';
import { provideRouter, RouterOutlet, withHashLocation } from '@angular/router';
import { provideAbsoluteUI } from '@absoluteui/angular';
import { EXAMPLES } from './examples';

@Component({ selector: 'frame-root', imports: [RouterOutlet], template: '<router-outlet />' })
class FrameRoot {}

// Theme, density, direction, and locale chosen in the docs toolbar (query string), as in
// the web-component frames (apps/site/src/examples/runtime.ts).
const THEMES = ['absolute-default', 'absolute-dark', 'absolute-high-contrast'] as const;
const DENSITIES = ['compact', 'comfortable', 'spacious'] as const;
const DIRECTIONS = ['ltr', 'rtl'] as const;
const LOCALES = ['en-US', 'en-GB', 'en-IN', 'de-DE', 'fr-FR', 'ja-JP', 'ar-EG', 'hi-IN'] as const;
const params = new URLSearchParams(location.search);
function pick<T extends string>(key: string, allowed: readonly T[], fallback: T): T {
  const value = params.get(key);
  return allowed.find((a) => a === value) ?? fallback;
}

let last = 0;
function report(): void {
  const height = Math.ceil(document.documentElement.getBoundingClientRect().height);
  if (height === last || window.parent === window) return;
  last = height;
  window.parent.postMessage({ type: 'aui-example-height', height }, location.origin);
}

async function start(): Promise<void> {
  const id = document.querySelector('frame-root')?.getAttribute('data-example') ?? '';
  const load = EXAMPLES[id];
  if (!load) throw new Error(\`Unknown Angular example: \${id}\`);
  const example = await load();
  await bootstrapApplication(FrameRoot, {
    providers: [
      provideZonelessChangeDetection(),
      provideRouter([{ path: '**', component: example.component }], withHashLocation()),
      provideAbsoluteUI({
        theme: pick('theme', THEMES, 'absolute-default'),
        density: pick('density', DENSITIES, 'comfortable'),
        direction: pick('dir', DIRECTIONS, 'ltr'),
        locale: pick('locale', LOCALES, 'en-US'),
        themeRuntime: { applyDirection: true },
      }),
      ...example.providers,
    ],
  });
  new ResizeObserver(report).observe(document.documentElement);
  report();
}

start().catch((error: unknown) => {
  console.error(error);
});
`;

