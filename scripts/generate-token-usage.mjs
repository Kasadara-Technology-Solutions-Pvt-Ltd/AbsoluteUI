// Generates the token-to-component index the Theme Designer compliance scoring uses to
// name affected components (SPEC section 10.4) from AI-readable metadata
// (metadata/<name>/tokens.json). The theme package cannot import component metadata,
// so the index is checked in and kept in sync by this generator.
// Usage: node scripts/generate-token-usage.mjs [--check]   (--check fails on drift)
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { root, readJson, fail } from './lib.mjs';

const meta = join(root, 'packages', 'components', 'metadata');
const target = join(root, 'packages', 'theme', 'src', 'designer', 'token-usage.ts');
const usage = new Map();
for (const name of readdirSync(meta).sort()) {
  const file = join(meta, name, 'tokens.json');
  if (name === 'schema' || !statSync(join(meta, name)).isDirectory() || !existsSync(file)) continue;
  const tokens = readJson(file);
  for (const t of [...tokens.tokens, ...(tokens.componentTokens ?? [])]) {
    if (!usage.has(t)) usage.set(t, []);
    usage.get(t).push(name);
  }
}
const lines = [
  '// Generated by scripts/generate-token-usage.mjs from component metadata. Do not edit.',
  '/** Components whose stylesheets read each token (SPEC section 10.4 affected components). */',
  'export const tokenUsage: Readonly<Record<string, readonly string[]>> = {',
  ...[...usage.keys()].sort().map((t) => `  '${t}': [${usage.get(t).map((c) => `'${c}'`).join(', ')}],`),
  '};',
  '',
];
const out = lines.join('\n');
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== out) fail(['token usage index drifted from metadata; run npm run generate:token-usage']);
  console.log(`check:token-usage: ok (${usage.size} tokens)`);
} else {
  writeFileSync(target, out);
  console.log(`generate:token-usage: wrote ${usage.size} tokens`);
}
